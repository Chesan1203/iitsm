class Level(Enum):
    """Impact, urgency and business criticality."""
    LOW = 1
    MEDIUM = 2
    HIGH = 3


class Priority(Enum):
    P1 = 1
    P2 = 2
    P3 = 3
    P4 = 4

    @property
    def label(self) -> str:
        return _PRIORITY_LABELS[self]


_PRIORITY_LABELS = {
    Priority.P1: "Critical",
    Priority.P2: "High",
    Priority.P3: "Medium",
    Priority.P4: "Low",
}


